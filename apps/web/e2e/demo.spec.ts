import type { Page } from "@playwright/test";
import { expect, test } from "./fixtures";

/**
 * Walks the demo stepper in the order of docs/DEMO_FLOW.md and asserts the golden numbers from
 * fixtures/golden/golden_values.json appear exactly as the server formats them.
 *
 * The same spec runs in both Playwright projects: `desktop` (mock data) and `live` (the real FastAPI
 * service). Only identifiers the server generates differ (approval ids, security-event ids), so those
 * assertions match by position or by pattern.
 */

async function next(page: Page, url: RegExp) {
  const button = page.getByTestId("demo-next");
  await expect(button).toBeEnabled();
  await button.click();
  await expect(page).toHaveURL(url);
}

test("demo stepper walks Scene 1, Scene 2, Scene 3 and Security with the golden numbers", async ({ page }) => {
  // `/` is the owner home now (it no longer redirects, and its owner reads open the sign-in dialog without a token),
  // so the walk starts on the mandate page; home.spec.ts covers `/`.
  await page.goto("/mandate");

  // Setup: reset, then the signed mandate and its three tiers.
  await next(page, /\/mandate/);
  await expect(page.getByRole("heading", { name: "Mandate", level: 1 })).toBeVisible();
  await expect(page.getByText("Signature valid")).toBeVisible();
  await expect(page.getByText("¥300,000.00").first()).toBeVisible();
  await expect(page.getByText("¥5,000.00").first()).toBeVisible();

  // Scene 1: the offer is a loan.
  await next(page, /\/inbox/);
  await expect(page.locator("mark")).toHaveCount(3);
  await expect(page.getByText("Immediate discount").first()).toBeVisible();

  await next(page, /\/trajectory/);
  await expect(page.getByText("¥28,326.92").first()).toBeVisible();
  await expect(page.getByText(/day 47/i).first()).toBeVisible();
  await expect(page.getByText("¥209,960.00").first()).toBeVisible();

  await next(page, /\/funding/);
  await expect(page.getByText("10.8417%").first()).toBeVisible();
  await expect(page.getByText("0.88%").first()).toBeVisible();
  // Each action carries the day it is requested and the day its cash lands (request day + the facility's lead time).
  const lands = page.getByTestId("plan-lands");
  await expect(lands).toHaveCount(2);
  await expect(lands.filter({ hasText: "Day 3" })).toHaveCount(1);
  // The plan card shows the API's landing day: the line draw lands on day 0, the invoice advance on day 3.
  await expect(lands.nth(0)).toHaveText("Day 0");
  await expect(lands.nth(1)).toHaveText("Day 3");

  await next(page, /\/verdict/);
  await expect(page.getByTestId("outcome-badge")).toContainText("REJECT");
  await expect(page.getByTestId("violation-AGG_CONCESSION_EXCEEDED")).toContainText("¥28,326.92");
  await expect(page.getByTestId("violation-RESERVE_BREACH")).toContainText(/day 47/i);
  // Four codes in both modes (the mock is recorded from the live API).
  await expect(page.getByTestId("violation-DISCOUNT_ABOVE_BREAK_EVEN")).toBeVisible();
  await expect(page.getByTestId("violation-EARLY_PAY_DEARER_THAN_PLAN")).toBeVisible();
  // Counter ids are generated by the server in live mode (CTR-<hash>), so pick the cards by their label.
  const counters = page.locator('[data-testid^="counter-"]');
  await expect(counters.filter({ hasText: "Option A" })).toContainText("¥3,027.77");
  await expect(counters.filter({ hasText: "Option A" })).toContainText("We will accept early settlement on up to ¥257,200 of this invoice at 0.85%, paid on or before day 2.");
  await expect(counters.filter({ hasText: "Option B" })).toContainText("¥1,260.00");

  await next(page, /\/verdict/);
  await expect(page.getByTestId("negotiation-result")).toContainText("DEAL");
  await expect(page.getByTestId("negotiation-result")).toContainText("Option A");

  await next(page, /\/ledger/);
  await expect(page.getByTestId("chain-status")).toContainText("Chain valid");
  await expect(page.getByText("Draw facility").first()).toBeVisible();

  // Scene 2: the buyer walks, the gap is still covered.
  await next(page, /\/verdict/);
  await expect(page.getByTestId("negotiation-result")).toContainText("NO DEAL");

  await next(page, /\/funding/);
  await expect(page.getByTestId("plan-total")).toHaveText("¥3,113.93");
  await expect(page.getByText("¥5,040.00").first()).toBeVisible();
  await expect(page.getByText("¥3,938.81").first()).toBeVisible();

  await next(page, /\/ledger/);
  await expect(page.getByText("Submit invoice for financing").first()).toBeVisible();
  await expect(page.getByTestId("chain-status")).toContainText("Chain valid");

  await next(page, /\/verdict/);
  await expect(page.getByTestId("outcome-badge")).toContainText("REJECT");
  await expect(page.getByTestId("violation-AGG_CONCESSION_EXCEEDED")).toContainText("¥28,326.92");

  // Scene 3: capex.
  await next(page, /\/capex/);
  await expect(page.getByText("¥380,885.77").first()).toBeVisible();
  await expect(page.getByTestId("structure-loan_36m")).toContainText("¥18,144.62");
  // The golden 1.13× (EBITDA ¥90,000 / (¥45,000 + ¥34,830.60)) is on books with nothing drawn. By Scene 3 the demo has
  // drawn ¥255,000 on invoice financing, whose interest-only service is ¥255,000 × 7.80% / 12 = ¥1,657.50, and the
  // ¥150,000 line draw adds ¥150,000 × 6.40% / 12 = ¥800.00: existing service ¥47,457.50, so month 1 is
  // 90,000 / (47,457.50 + 34,830.60) = 1.0937 -> 1.09×. The 18-month term is also an illustration (the loan is 36 months).
  await expect(page.getByTestId("structure-loan_18m")).toContainText("1.09");
  await expect(page.getByTestId("structure-loan_18m")).toContainText("Illustration only");
  await expect(page.getByTestId("capex-as-of")).toContainText("day 0");

  await next(page, /\/approvals/);
  // The queue reason, as the server words it.
  await expect(page.getByText(/apply for facility FAC-ETL/i).first()).toBeVisible();

  // Security: the FastCapital message.
  await next(page, /\/security/);
  const events = page.locator('[data-testid^="event-"]');
  // The three refusals (plus, in live mode, the compiler's injection flags as INJECTION events).
  await expect(events.first()).toBeVisible();
  expect(await events.count()).toBeGreaterThanOrEqual(3);
  await expect(events.filter({ hasText: "UNKNOWN_COUNTERPARTY" }).first()).toBeVisible();
  await expect(events.filter({ hasText: "UNEVIDENCED_CLAIM" }).first()).toBeVisible();
  await expect(events.filter({ hasText: "DATA_EXTRACTION" }).first()).toBeVisible();
  await expect(page.getByText("¥0.00").first()).toBeVisible();
  // The original message with the triggering spans highlighted, and the exact reply that went out.
  await expect(page.getByRole("group", { name: /Message from/ }).locator("mark").first()).toBeVisible();
  await expect(page.getByRole("heading", { name: "Reply sent" })).toBeVisible();
  await expect(page.locator("#sec-reply blockquote")).not.toBeEmpty();

  await next(page, /\/evidence/);
  const [download] = await Promise.all([page.waitForEvent("download"), page.getByTestId("download-evidence").click()]);
  expect(download.suggestedFilename()).toBe("termsledger-evidence.jsonl");
  await expect(page.getByTestId("demo-next")).toBeDisabled();
});

test("Tier 2 approval queue approves the capex loan and logs it", async ({ page }) => {
  await page.goto("/mandate");
  for (let i = 0; i < 13; i++) {
    const button = page.getByTestId("demo-next");
    await expect(button).toBeEnabled();
    await button.click();
    // Wait for the step to complete (the counter advances after the server work), not just for the button to re-enable.
    await expect(page.getByRole("region", { name: "Guided demo" }).locator("[aria-live=polite]")).toContainText(`${i + 1}/15`);
  }
  await expect(page).toHaveURL(/\/approvals/);
  await page.getByRole("button", { name: "Approve" }).first().click();
  await expect(page.getByText("Approved").first()).toBeVisible();
  await page.goto("/ledger");
  await expect(page.getByTestId("chain-status")).toContainText("Chain valid");
});

test("the label toggle switches the UI to Chinese and back", async ({ page }) => {
  await page.goto("/mandate");
  await page.getByLabel("中文").check();
  await expect(page.getByRole("heading", { name: "授权书", level: 1 })).toBeVisible();
  await page.getByLabel("English").check();
  await expect(page.getByRole("heading", { name: "Mandate", level: 1 })).toBeVisible();
});

test("reset clears the session back to the demo's starting point", async ({ page }) => {
  await page.goto("/mandate");
  await page.getByTestId("demo-next").click();
  await expect(page).toHaveURL(/\/mandate/);
  await page.getByTestId("demo-next").click();
  await expect(page).toHaveURL(/\/inbox/);
  await page.getByTestId("demo-reset").click();
  await expect(page).toHaveURL(/\/mandate/);
  await page.goto("/ledger");
  // The demo opens on the three demo documents read by the agent and confirmed by the owner; nothing else is logged.
  const ops = page.locator("#operations tbody tr");
  await expect(ops).toHaveCount(3);
  await expect(ops.filter({ hasText: "Confirm document" })).toHaveCount(3);
  await expect(page.getByTestId("chain-status")).toContainText("3 entries");
});
