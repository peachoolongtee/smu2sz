/**
 * Walks the demo stepper in the order of docs/DEMO_FLOW.md and asserts the golden numbers from
 * fixtures/golden/golden_values.json appear exactly as the server formats them.
 *
 * The same spec runs in both Playwright projects: `desktop` (mock data) and `live` (the real FastAPI
 * service). Only identifiers the server generates differ (approval ids, security-event ids), so those
 * assertions match by position or by pattern.
 */

async function next(page: Page, url: RegExp) {
  const button = page.getByTestId("demo-next");
  await expect(button).toBeEnabled();
  await button.click();
  await expect(page).toHaveURL(url);
}

